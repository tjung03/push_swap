#include "push_swap.h"

// 미완 음수 등의 부호문제
long long	ft_pw_atoi(char *s)
{
	long long	num;
	int	i;

	num = 0;
	i = 0;
	if (s[0] == '-' || s[0] == '+')
		i++;
	while (s[i] >= '0' && s[i] <= '9')
	{
		num = num * 10 + (s[i] - 48);
		i++;
	}
	if (s[0] == '-')
		num *= -1;
	return (num);
}
